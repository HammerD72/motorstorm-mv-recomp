def has_key(data, digests=DIGESTS):
    # Recover candidate contiguous byte literals or hex strings without storing keys.
    values = re.findall(rb'0x([0-9a-fA-F]{1,2})(?![0-9a-fA-F])', data)
    byte_literals = bytes(int(x,16) for x in values)
    candidates = [byte_literals]
    for value in re.findall(rb'(?<![0-9a-fA-F])[0-9a-fA-F]{32,}(?![0-9a-fA-F])', data):
        if len(value)%2 == 0:
            candidates.append(bytes.fromhex(value.decode()))
    return any(hashlib.sha256(value[i:i+16]).hexdigest() in digests
               for value in candidates for i in range(max(0,len(value)-15)))

def problem(name, data):
    p = PurePosixPath(name)
    parts = p.parts
    if name != '.github/workflows/source-audit.yml' and name not in TOP and (len(parts)<2 or parts[0] not in DIRS):
        return 'not an approved glue path; put local inputs in game/ or temp/'
    if any(x.lower() in PRIVATE for x in parts):
        return 'private/generated directory; keep local'
    if name.startswith('vendor/ps3recomp/tools/') and name.removeprefix('vendor/ps3recomp/tools/') not in VENDOR_TOOLS:
        return 'not a reviewed generation dependency; preserve in temp/legacy/vendor_reference/'
    if name.startswith('config/') and name != 'config/local.example.json':
        return 'only config/local.example.json is publishable'
    if p.suffix.lower() in BAD:
        return 'game/binary/media/capture/key payload'
    if p.name in {'ps3_edat_keys.h','ps3_sdata_keys.h','keys.json'}:
        return 'private key material belongs in game/private_keys/'
    if p.name.startswith(('ppu_recomp.', 'spu_recomp.', 'test_')) or p.name.endswith(('.functions.json','.imports.json','selftest.py')):
        return 'generated guest code/metadata or unreviewed instruction fixture'
    if b'\0' in data or data.startswith(MAGIC):
        return 'binary payload'
    if data.lstrip().startswith((b'/* Auto-generated by ppu_lifter', b'/* Auto-generated by spu_lifter')):
        return 'lifted original guest instructions'
    if has_key(data):
        return 'bundled platform key signature; supply private headers/PS3_KEYS_FILE'
    return None

def indexed_blobs():
    git = ['git', '-c', 'safe.directory='+ROOT.as_posix(), '-C', str(ROOT)]
    entries = subprocess.check_output(git+['ls-files','--stage','-z']).split(b'\0')[:-1]
    records = []
    for entry in entries:
        head, path = entry.split(b'\t',1)
        mode, oid, stage = head.decode().split()
        if stage != '0' or mode not in {'100644','100755'}:
            raise SystemExit('Unsupported index entry: '+path.decode())
        records.append((path.decode(),oid))
    request = ''.join(oid+'\n' for _,oid in records).encode()
    output = subprocess.run(git+['cat-file','--batch'], input=request, stdout=subprocess.PIPE, check=True).stdout
    offset = 0
    for path,oid in records:
        end=output.index(b'\n',offset)
        header=output[offset:end].decode().split()
        if header[0]!=oid or header[1]!='blob':raise SystemExit('Invalid index blob: '+path)
        size=int(header[2]);offset=end+1
        data=output[offset:offset+size];offset+=size+1
        yield path,data

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--self-test',action='store_true')
    args=parser.parse_args()
    if args.self_test:
        cases=[('src/hidden.h',b'\x7fELFtest'),
               ('build/generated/named/ppu/x.cpp',b'int x;'),
               ('audio_export/GUI/x.ogg',b'OggS'),
               ('src/ppu_recomp.cpp_003.cpp',b'guest'),
               ('src/hidden.cpp',b'/* Auto-generated by ppu_lifter.py */'),
               ('src/ps3_edat_keys.h',b'private'),
               ('vendor/ps3recomp/tools/test_fixture.py',b'guest instructions'),
               ('vendor/ps3recomp/tools/stderr_revert2.txt',b'old diagnostic output'),
               ('config/other.json',b'personal')]
        for name,data in cases:assert problem(name,data),name
        synthetic=bytes(range(16))
        digest={hashlib.sha256(synthetic).hexdigest()}
        assert has_key(('key='+synthetic.hex()).encode(),digest)
        assert has_key((','.join(hex(x) for x in synthetic)).encode(),digest)
        assert has_key((','.join('0x%02x'%x for x in synthetic)).encode(),digest)
        assert problem('src/main.cpp',b'int main() {}') is None
        print('PASS: payload/generated-code/private-key rejection cases')
        return
    count=0;errors=[]
    for name,data in indexed_blobs():
        count+=1
        reason=problem(name,data)
        if reason:errors.append(f'{name}: {reason}')
    if not count:raise SystemExit('Empty index: stage reviewed glue first')
    if errors:raise SystemExit('\n'.join(errors))
    print(f'PASS: {count} staged source files; format/path/key-signature audit')
    print('Text provenance review remains required; no legal immunity is implied.')

if __name__=='__main__':
    main()
